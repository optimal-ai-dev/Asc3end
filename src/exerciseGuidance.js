// The catalogue's pose-level guidance (exerciseData.js POSE_SETUP_EXECUTION) is accurate for the
// movement the pose draws — "lie on a bench and press the bar to lockout" is right for a bench
// press. But a pose was reused for anatomically different exercises (Pec Deck and cable flies share
// the press pose; Dead Bug, Pallof Press and Ab Wheel share the plank pose; Tibialis Raises share
// the calf-raise pose), which produced instructions that taught the wrong movement. Each family
// below matches by NAME (original, auditable regexes) and supplies its own setup / execution /
// cues. getExerciseGuidance() resolves: per-exercise override -> family here -> pose default.
//
// All wording is original. No text is copied from any exercise database or competitor.
//
// This file must stay free of imports so exerciseData.js can import it without a cycle.

