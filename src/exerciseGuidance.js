/** First matching family for an exercise-like { name, equipment, pose } or null. */
export function findGuidanceFamily(ex) {
  if (!ex || typeof ex.name !== "string") return null;
  return GUIDANCE_FAMILIES.find((fam) => {
    try { return fam.test(ex); } catch (e) { return false; }
  }) || null;
}
